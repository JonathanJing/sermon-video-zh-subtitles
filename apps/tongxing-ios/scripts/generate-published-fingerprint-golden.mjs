/** Regenerate compact cross-language fixtures from the production browser DSP.
 * node apps/tongxing-ios/scripts/generate-published-fingerprint-golden.mjs
 * Synthetic chirps only; this is compatibility evidence, not microphone QA.
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {fingerprint, matchFingerprint} from '../../../experiments/sermon-dubbing-poc/web/fingerprint-core.mjs';

function signal(rate, variant = 0) {
  return Float32Array.from({length: rate * 10}, (_, i) => {
    const t = i / rate;
    return .18 * Math.sin(2 * Math.PI * ((300 + variant * 370) * t + 45 * t * t + 90 * Math.sin(1.7 * t)))
      + .12 * Math.sin(2 * Math.PI * ((1100 + variant * 230) * t - 29 * t * t + 65 * Math.sin(2.3 * t)))
      + .08 * Math.sin(2 * Math.PI * ((2100 - variant * 410) * t + 13 * t * t + 40 * Math.sin(.9 * t)));
  });
}
function index(landmarks, shifts = [625]) {
  const postings = {};
  for (const [hash, time] of landmarks) for (const shift of shifts) (postings[hash] ??= []).push(time + shift);
  for (const values of Object.values(postings)) values.sort((a, b) => a - b);
  return {schemaVersion:'sermon-landmark-index-v1', algorithmVersion:'spectral-landmarks-v1',
    sampleRate:8000, hopSize:256, durationSeconds:90, postings};
}
export function generateGolden() {
  const unrelated = fingerprint(signal(8000, 1), 8000);
  const cases = [8000, 44100, 48000].map(sampleRate => {
    const query = fingerprint(signal(sampleRate), sampleRate);
    const matchingIndex = index(query.landmarks);
    const expectedMatch = matchFingerprint(query, matchingIndex);
    const expectedAmbiguous = matchFingerprint(query, index(query.landmarks, [625, 1562]));
    const expectedUnrelated = matchFingerprint(query, index(unrelated.landmarks));
    const expectedSilence = matchFingerprint(fingerprint(new Float32Array(sampleRate * 10), sampleRate), matchingIndex);
    if (!expectedMatch.matched || expectedAmbiguous.diagnostics.reason !== 'ambiguous' || expectedUnrelated.matched)
      throw Error('Synthetic signal did not exercise required outcomes');
    return {sampleRate, query, expectedMatch, expectedAmbiguous, expectedUnrelated, expectedSilence};
  });
  return {provenance:'Generated by production web/fingerprint-core.mjs; synthetic chirps, no recorded media', unrelatedLandmarks:unrelated.landmarks, cases};
}

export function compareGolden(actual, expected) {
  let mismatchCount = 0;
  const differences = [];
  function difference(path) { mismatchCount++; if (differences.length < 32) differences.push(path); }
  function compare(a, b, path) {
    if (typeof a === 'number' && typeof b === 'number') {
      // Accommodate harmless libm floating-point differences only; quantized
      // landmark integers, boolean acceptance and reason codes remain exact.
      if (!Number.isFinite(a) || !Number.isFinite(b) || (Number.isInteger(a) || Number.isInteger(b) ? a !== b : Math.abs(a - b) > 1e-9)) difference(path);
    } else if (Array.isArray(a) && Array.isArray(b)) {
      if (a.length !== b.length) difference(path + '.length');
      for (let i = 0; i < Math.min(a.length, b.length); i++) compare(a[i], b[i], path + '[' + i + ']');
    } else if (a && b && typeof a === 'object' && typeof b === 'object' && !Array.isArray(a) && !Array.isArray(b)) {
      const keys = Object.keys(a).sort();
      if (JSON.stringify(keys) !== JSON.stringify(Object.keys(b).sort())) difference(path + '.keys');
      for (const key of keys) compare(a[key], b[key], path + '.' + key);
    } else if (a !== b) difference(path);
  }
  compare(actual, expected, 'fixture');
  return {mismatchCount, differences};
}

const defaultFixture = new URL('../Core/Tests/TongxingCoreTests/Fixtures/published-fingerprint.golden.json', import.meta.url);
export function checkGolden(fixture = defaultFixture) {
  const bytes = readFileSync(fixture);
  if (bytes.length > 4 * 1024 * 1024) throw new Error('Fixture exceeds bound');
  const actual = generateGolden(), expected = JSON.parse(bytes);
  const comparison = compareGolden(actual, expected);
  const sha = value => createHash('sha256').update(value).digest('hex');
  return {
    schemaVersion: 'sermon-fingerprint-contract-baseline-v1',
    status: comparison.mismatchCount ? 'failed' : 'synthetic_contract_passed',
    fixtureSha256: sha(bytes),
    algorithmSha256: sha(readFileSync(new URL('../../../experiments/sermon-dubbing-poc/web/fingerprint-core.mjs', import.meta.url))),
    generatorSha256: sha(readFileSync(new URL(import.meta.url))),
    algorithmVersion: 'spectral-landmarks-v1', indexSchemaVersion: 'sermon-landmark-index-v1',
    evidenceScope: 'deterministic_synthetic_browser_contract',
    sampleRates: actual.cases.map(c => c.sampleRate),
    cases: actual.cases.flatMap(c => ['Match', 'Ambiguous', 'Unrelated', 'Silence'].map(kind => ({
      sampleRate: c.sampleRate, scenario: kind.toLowerCase(),
      matched: c['expected' + kind].matched, reason: c['expected' + kind].diagnostics.reason,
    }))),
    ...comparison,
    swiftParity: 'not_run', legacyPackedParity: 'not_run', deviceAcceptance: 'not_run', venueAcceptance: 'not_run',
    promotionAllowed: false,
  };
}

function main(args) {
  if (args.length === 1 && args[0] === '--help') {
    console.log('Usage: node generate-published-fingerprint-golden.mjs [--check [--fixture PATH] [--report PATH]]\nNo arguments regenerates the checked-in synthetic fixture. --check never modifies it. Reports must not already exist.');
    return;
  }
  if (args.length === 0) {
    const golden = generateGolden();
    writeFileSync(defaultFixture, JSON.stringify(golden) + '\n');
    console.log(golden.cases.map(c => ({rate:c.sampleRate, peaks:c.query.peakCount, pairs:c.query.landmarks.length,
      match:c.expectedMatch.queryStartSeconds, unrelated:c.expectedUnrelated.diagnostics.reason})));
    return;
  }
  if (args[0] !== '--check') throw new Error('Expected --check or --help');
  let fixture = defaultFixture, reportPath;
  const seen = new Set();
  for (let i = 1; i < args.length; i += 2) {
    const flag = args[i], value = args[i + 1];
    if (!['--fixture', '--report'].includes(flag) || !value || value.startsWith('--') || seen.has(flag)) throw new Error('Invalid check arguments');
    seen.add(flag);
    if (flag === '--fixture') fixture = value; else reportPath = value;
  }
  const report = checkGolden(fixture);
  if (reportPath) writeFileSync(reportPath, JSON.stringify(report, null, 2) + '\n', {flag: 'wx'});
  console.log(JSON.stringify(report));
  if (report.status === 'failed') process.exitCode = 1;
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  try { main(process.argv.slice(2)); }
  catch { console.error('Fingerprint baseline check failed; verify fixture and output arguments.'); process.exitCode = 1; }
}
