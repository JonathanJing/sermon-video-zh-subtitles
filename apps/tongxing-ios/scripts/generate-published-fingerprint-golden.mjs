/** Regenerate compact cross-language fixtures from the production browser DSP.
 * node apps/tongxing-ios/scripts/generate-published-fingerprint-golden.mjs
 * Synthetic chirps only; this is compatibility evidence, not microphone QA.
 */
import {writeFileSync} from 'node:fs';
import {fingerprint, matchFingerprint} from '../../../experiments/sermon-dubbing-poc/web/fingerprint-core.mjs';

function signal(rate, variant = 0) {
  return Float32Array.from({length: rate * 10}, (_, i) => {
    const t = i / rate;
    return .18 * Math.sin(2 * Math.PI * ((300 + variant * 370) * t + 45 * t * t + 90 * Math.sin(1.7 * t)))
      + .12 * Math.sin(2 * Math.PI * ((1100 + variant * 230) * t - 29 * t * t + 65 * Math.sin(2.3 * t)))
      + .08 * Math.sin(2 * Math.PI * ((2100 - variant * 410) * t + 13 * t * t + 40 * Math.sin(.9 * t)));
  });
}
function index(landmarks, shifts = [625]) {
  const postings = {};
  for (const [hash, time] of landmarks) for (const shift of shifts) (postings[hash] ??= []).push(time + shift);
  for (const values of Object.values(postings)) values.sort((a, b) => a - b);
  return {schemaVersion:'sermon-landmark-index-v1', algorithmVersion:'spectral-landmarks-v1',
    sampleRate:8000, hopSize:256, durationSeconds:90, postings};
}
const unrelated = fingerprint(signal(8000, 1), 8000);
const cases = [8000, 44100, 48000].map(sampleRate => {
  const query = fingerprint(signal(sampleRate), sampleRate);
  const matchingIndex = index(query.landmarks);
  const expectedMatch = matchFingerprint(query, matchingIndex);
  const expectedAmbiguous = matchFingerprint(query, index(query.landmarks, [625, 1562]));
  const expectedUnrelated = matchFingerprint(query, index(unrelated.landmarks));
  const expectedSilence = matchFingerprint(fingerprint(new Float32Array(sampleRate * 10), sampleRate), matchingIndex);
  if (!expectedMatch.matched || expectedAmbiguous.diagnostics.reason !== 'ambiguous' || expectedUnrelated.matched)
    throw Error('Synthetic signal did not exercise required outcomes');
  return {sampleRate, query, expectedMatch, expectedAmbiguous, expectedUnrelated, expectedSilence};
});
const output = new URL('../Core/Tests/TongxingCoreTests/Fixtures/published-fingerprint.golden.json', import.meta.url);
writeFileSync(output, JSON.stringify({provenance:'Generated by production web/fingerprint-core.mjs; synthetic chirps, no recorded media', unrelatedLandmarks:unrelated.landmarks, cases}) + '\n');
